-- Optional manual initialization (the API also creates this table on first DB request).
-- Run this inside the supportdb database. Script is idempotent and preserves records.
CREATE TABLE IF NOT EXISTS tickets (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL,
    description varchar(4000) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'New' CHECK (status IN ('New', 'InProgress', 'Closed')),
    created_at timestamptz NOT NULL DEFAULT NOW()
);
