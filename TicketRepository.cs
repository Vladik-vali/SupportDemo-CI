using Npgsql;

namespace SupportDemo;

public sealed class TicketRepository(NpgsqlDataSource dataSource)
{
    private static readonly string CreateTableSql = """
        CREATE TABLE IF NOT EXISTS tickets (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title varchar(200) NOT NULL,
            description varchar(4000) NOT NULL,
            status varchar(20) NOT NULL DEFAULT 'New'
                CHECK (status IN ('New', 'InProgress', 'Closed')),
            created_at timestamptz NOT NULL DEFAULT NOW()
        );
        """;

    private static async Task EnsureSchemaAsync(NpgsqlConnection connection, CancellationToken ct)
    {
        await using var command = new NpgsqlCommand(CreateTableSql, connection);
        await command.ExecuteNonQueryAsync(ct);
    }

    public async Task<Ticket> CreateAsync(string title, string description, CancellationToken ct)
    {
        await using var connection = await dataSource.OpenConnectionAsync(ct);
        await EnsureSchemaAsync(connection, ct);
        await using var command = new NpgsqlCommand("""
            INSERT INTO tickets (title, description, status)
            VALUES (@title, @description, 'New')
            RETURNING id, title, description, status, created_at;
            """, connection);
        command.Parameters.AddWithValue("title", title);
        command.Parameters.AddWithValue("description", description);
        await using var reader = await command.ExecuteReaderAsync(ct);
        await reader.ReadAsync(ct);
        return ReadTicket(reader);
    }

    public async Task<List<Ticket>> GetAllAsync(CancellationToken ct)
    {
        await using var connection = await dataSource.OpenConnectionAsync(ct);
        await EnsureSchemaAsync(connection, ct);
        await using var command = new NpgsqlCommand("""
            SELECT id, title, description, status, created_at
            FROM tickets ORDER BY id;
            """, connection);
        await using var reader = await command.ExecuteReaderAsync(ct);
        var tickets = new List<Ticket>();
        while (await reader.ReadAsync(ct))
            tickets.Add(ReadTicket(reader));
        return tickets;
    }

    public async Task<Ticket?> GetByIdAsync(int id, CancellationToken ct)
    {
        await using var connection = await dataSource.OpenConnectionAsync(ct);
        await EnsureSchemaAsync(connection, ct);
        await using var command = new NpgsqlCommand("""
            SELECT id, title, description, status, created_at
            FROM tickets WHERE id = @id;
            """, connection);
        command.Parameters.AddWithValue("id", id);
        await using var reader = await command.ExecuteReaderAsync(ct);
        return await reader.ReadAsync(ct) ? ReadTicket(reader) : null;
    }

    public async Task<Ticket?> UpdateStatusAsync(int id, string status, CancellationToken ct)
    {
        await using var connection = await dataSource.OpenConnectionAsync(ct);
        await EnsureSchemaAsync(connection, ct);
        await using var command = new NpgsqlCommand("""
            UPDATE tickets SET status = @status WHERE id = @id
            RETURNING id, title, description, status, created_at;
            """, connection);
        command.Parameters.AddWithValue("id", id);
        command.Parameters.AddWithValue("status", status);
        await using var reader = await command.ExecuteReaderAsync(ct);
        return await reader.ReadAsync(ct) ? ReadTicket(reader) : null;
    }

    private static Ticket ReadTicket(NpgsqlDataReader reader) => new(
        reader.GetInt32(0),
        reader.GetString(1),
        reader.GetString(2),
        reader.GetString(3),
        reader.GetDateTime(4));
}
